# area_calculator.py
from shapes import Shape  # Импортируем абстрактный класс Shape для указания типа

class AreaCalculator:
    """
    Класс для расчёта общей площади коллекции фигур.
    Демонстрирует принцип абстракции: работает с любым объектом типа Shape,
    не зная его конкретной реализации.
    """

    @staticmethod
    def total_area(shapes: list[Shape]) -> float:
        """
        Статический метод для расчёта суммы площадей всех фигур в списке.
        :param shapes: список объектов, наследующих от Shape
        :return: сумма площадей всех фигур (число с плавающей точкой)
        """
        total = 0.0  # Инициализируем общую площадь нулём
        for shape in shapes:  # Перебираем все фигуры в списке
            total += shape.area()  # Вызываем метод area() — каждая фигура считает свою площадь сама
        return total  # Возвращаем итоговую сумму
