from abc import ABC, abstractmethod  # Импортируем ABC (Abstract Base Class) и декоратор abstractmethod для создания абстрактных классов

class Shape(ABC):
    """
    Абстрактный класс Shape.
    ABC означает, что нельзя создать экземпляр этого класса напрямую.
    Определяет контракт: все наследники должны реализовать метод area().
    """

    @abstractmethod
    def area(self) -> float:
        """
        Абстрактный метод — должен быть реализован в каждом наследнике.
        Возвращает площадь фигуры как число с плавающей точкой.
        """
        pass  # Тело метода пустое — реализация будет в конкретных классах

class Rectangle(Shape):
    """
    Конкретная реализация фигуры — прямоугольник.
    Наследует от абстрактного класса Shape.
    """

    def __init__(self, width: float, height: float):
        """
        Конструктор класса Rectangle.
        :param width: ширина прямоугольника (положительное число)
        :param height: высота прямоугольника (положительное число)
        """
        self.width = width
        self.height = height

    def area(self) -> float:
        """
        Реализация метода area() для прямоугольника.
        Формула: площадь = ширина × высота.
        """
        return self.width * self.height

class Circle(Shape):
    """
    Конкретная реализация фигуры — круг.
    Наследует от абстрактного класса Shape.
    """

    def __init__(self, radius: float):
        """
        Конструктор класса Circle.
        :param radius: радиус круга (положительное число)
        """
        self.radius = radius

    def area(self) -> float:
        """
        Реализация метода area() для круга.
        Формула: площадь = π × радиус². Используем приближение π ≈ 3.14159.
        """
        import math
        return math.pi * (self.radius ** 2)

class Triangle(Shape):
    """
    Конкретная реализация фигуры — треугольник (прямоугольный).
    Наследует от абстрактного класса Shape.
    """

    def __init__(self, base: float, height: float):
        """
        Конструктор класса Triangle.
        :param base: основание треугольника
        :param height: высота треугольника
        """
        self.base = base
        self.height = height

    def area(self) -> float:
        """
        Реализация метода area() для треугольника.
        Формула: площадь = (основание × высота) / 2.
        """
        return (self.base * self.height) / 2
